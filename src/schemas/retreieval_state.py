from __future__ import annotations

from datetime import datetime
from typing import Any, TypedDict
from uuid import UUID


class RetrievalState(TypedDict, total=False):
    # ------------------------------------------------------------------
    # Inputs
    # ------------------------------------------------------------------

    user_id: UUID

    query_text: str

    messages: list[Any]
    # Conversation history (excluding the current user message)

    # ------------------------------------------------------------------
    # Query Router
    # ------------------------------------------------------------------

    needs_retrieval: bool

    # ------------------------------------------------------------------
    # Coreference Resolver
    # ------------------------------------------------------------------

    resolved_query_text: str

    # ------------------------------------------------------------------
    # Shared Query Embedding
    # ------------------------------------------------------------------

    query_embedding: list[float]

    # ------------------------------------------------------------------
    # Semantic Retrieval
    # ------------------------------------------------------------------

    semantic_results: list[dict]

    # ------------------------------------------------------------------
    # Episodic Retrieval
    # ------------------------------------------------------------------

    episodic_results: list[dict]

    # ------------------------------------------------------------------
    # Contextual Reinstatement
    # ------------------------------------------------------------------

    enriched_episodic_results: list[dict]

    # ------------------------------------------------------------------
    # Fusion
    # ------------------------------------------------------------------

    fused_results: list[dict]

    # ------------------------------------------------------------------
    # Context Validation
    # ------------------------------------------------------------------

    context_notes: list[str]

    validated_context: list[dict]

    # ------------------------------------------------------------------
    # Context Packer
    # ------------------------------------------------------------------

    packed_context: list[dict]

    packed_token_count: int

    # ------------------------------------------------------------------
    # Diagnostics
    # ------------------------------------------------------------------

    errors: list[dict[str, Any]]